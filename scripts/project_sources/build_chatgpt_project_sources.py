def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", required=True)
    ap.add_argument("--execution-base-sha", required=True)
    ap.add_argument("--open-pr-dir", required=True, help="dir containing OPEN_PRS_INITIAL.json and open-pr-<N>.json")
    ap.add_argument("--source-set", default="scripts/project_sources/source_set_v4.json")
    ap.add_argument("--pr-classifications", default="scripts/project_sources/pr_classifications.json")
    ap.add_argument("--output-dir", required=True)
    ap.add_argument("--generated-at", required=True, help="ISO-8601 UTC timestamp, e.g. 2026-07-28T00:00:00Z")
    ap.add_argument("--handoff-path", help="optional generated operator handoff path")
    args = ap.parse_args()

    repo_root = Path(args.repo_root).resolve()
    output_dir = Path(args.output_dir).resolve()
    validate_output_dir(repo_root, output_dir)
    # Clear rather than merge: reusing --output-dir across runs would otherwise
    # let stale files survive into the ZIP. Guard the caller-controlled path
    # before cleanup, then remove only an existing validated package directory.
    if output_dir.exists():
        shutil.rmtree(output_dir)
    upload_dir = output_dir / "UPLOAD_FILES"
    upload_dir.mkdir(parents=True, exist_ok=True)

    source_set = json.loads((repo_root / args.source_set).read_text())
    classifications = json.loads((repo_root / args.pr_classifications).read_text())
    open_pr_dir = Path(args.open_pr_dir).resolve()
    prs = load_captured_prs(open_pr_dir)
    initial = json.loads((open_pr_dir / "OPEN_PRS_INITIAL.json").read_text())
    initial = [pr for pr in initial if pr.get("number") != SELF_PR_NUMBER]

    if len(prs) != len(initial):
        raise SystemExit(f"FATAL: captured per-PR file count ({len(prs)}) != initial inventory count ({len(initial)})")

    copied_entries = build_copied_slots(repo_root, args.execution_base_sha, source_set, upload_dir)

    pr_entries = build_pr_ledger_entries(prs, classifications)
    material_count = sum(1 for e in pr_entries if e["classification"] in MATERIAL_PR_CLASSIFICATIONS)
    disposition = "CURRENT_MAIN_VALID_PENDING_OPEN_PR_REFRESH" if material_count > 0 else "CURRENT_MAIN_VALID"

