def render_source_resolution_report(copied_entries: list[dict]) -> str:
    lines = ["# SOURCE_RESOLUTION_REPORT", "", "For every slot: logical slot, selected source, rejected candidates, authority class, blob SHA, content SHA-256, byte count, rationale.", ""]
    for e in copied_entries:
        lines.append(f"## Slot {e['slot']:02d} -- {e['bundle_filename']}")
        lines.append("")
        lines.append(f"- Selected source path: `{e['source_path']}`")
        lines.append(f"- Authority class: {e['authority_class']}")
        lines.append(f"- Freshness class: {e['freshness_class']}")
        lines.append(f"- Source blob SHA: `{e['source_blob_sha']}`")
        lines.append(f"- Content SHA-256: `{e['sha256']}`")
        lines.append(f"- Bytes: {e['bytes']}")
        lines.append(f"- Rationale: {e['notes'][0]}")
