def build_pr_ledger_entries(prs: list[dict], classifications: dict) -> list[dict]:
    entries = []
    for pr in prs:
        n = str(pr["number"])
        c = classifications["classifications"].get(n)
        if c is None:
            raise SystemExit(f"FATAL: open PR #{n} has no classification entry -- fail-closed")
        if c["classification"] not in VALID_PR_CLASSIFICATIONS:
            raise SystemExit(
                f"FATAL: open PR #{n} has unrecognized classification "
                f"'{c['classification']}' -- must be one of {sorted(VALID_PR_CLASSIFICATIONS)}"
            )
        files = [f["path"] for f in pr.get("files", [])]
        # Always recompute from the captured data rather than trusting a
        # self-reported capture_complete flag: a future capture run with a
        # paginator bug could set the field to True incorrectly, and trusting
        # it would silently bypass the fail-closed check below.
        capture_complete = len(files) == pr.get("changedFiles", -1)
        if not capture_complete and c["classification"] != "SUPERSEDED_OR_CONFLICTING":
            # A truncated/incomplete file capture is only tolerated for PRs
            # whose classification does not depend on path-level intersection
            # (see #1123's evidence, which discloses capture_complete=false
            # explicitly). Any other classification with an incomplete
            # capture is a fail-closed error, not a silent gap.
            raise SystemExit(
                f"FATAL: PR #{n} has an incomplete file capture "
                f"({len(files)}/{pr.get('changedFiles')} files) but is classified "
                f"'{c['classification']}', which requires full path intersection evidence"
            )
        entries.append(
            {
                "pr_number": pr["number"],
                "title": pr["title"],
                "url": pr["url"],
                "state": pr["state"],
                "is_draft": pr["isDraft"],
                "base_branch": pr["baseRefName"],
                "head_branch": pr["headRefName"],
                "head_sha": pr["headRefOid"],
                "merge_state_status": pr["mergeStateStatus"],
                "updated_at": pr["updatedAt"],
                "changed_file_count": pr.get("changedFiles", len(files)),
                "capture_complete": capture_complete,
                "watched_path_sample": files[:15],
                "classification": c["classification"],
                "evidence": c["evidence"],
                "current_main_effect": c["current_main_effect"],
                "action_if_merged": c["action_if_merged"],
                "source_slots_affected": c["source_slots_affected"],
                "contradiction_or_overlap_notes": c["contradiction_or_overlap_notes"],
                "confidence": c["confidence"],
            }
        )
    return entries


