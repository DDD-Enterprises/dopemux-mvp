#!/usr/bin/env python3
"""Deterministic assembler for the TP-DMX-FDOS-004 ChatGPT Project 40-source upload set.

Reads the resolved 37-slot source spec (source_set_v4.json) and the pre-captured
open-PR evidence (proof/.../open-pr-*.json, OPEN_PRS_INITIAL.json) plus their
classifications (pr_classifications.json), copies current-main source bytes
byte-for-byte via `git show <EXECUTION_BASE_SHA>:<path>`, and emits the
UPLOAD_FILES/ directory, source manifest, open-PR impact ledger, freshness
policy, and supporting reports under out/chatgpt-project-upload-set/.

No network calls. All open-PR data is consumed from previously captured
evidence files -- this script never invokes `gh`.
"""
from __future__ import annotations

import argparse
import hashlib
