import sys
from pathlib import Path

PACKET_ID = "TP-DMX-FDOS-004-CHATGPT-PROJECT-SOURCE-REFRESH"
REPO = "DDD-Enterprises/dopemux-mvp"

FRESHNESS_POLICY_TEXT = """# 38_SOURCE_FRESHNESS_POLICY

> GENERATED ARTIFACT -- non-authoritative. This file describes how to interpret
> the freshness of every other file in this upload set. It is generated by
> `scripts/project_sources/build_chatgpt_project_sources.py` for packet
> `{packet_id}` and is bound to `execution_base_sha: {execution_base_sha}`.
> It does not itself establish runtime, governance, or architectural truth.

## 1. Freshness Classes

- `LIVE_RESOLVE` -- must always be re-resolved live against the running system
  or the current open-PR inventory; never trust a snapshot for these claims.
- `VOLATILE_14_DAYS` -- treat as stale after 14 days from `generated_at` below,
  or immediately if `origin/main` has moved past `execution_base_sha` for the
  file's own path.
- `SYSTEM_SNAPSHOT_30_DAYS` -- system/architecture reference docs; treat as
  stale after 30 days or on any merged PR touching the described service.
- `STABLE_CONTRACT_90_DAYS` -- schemas and contracts that change rarely; treat
  as stale after 90 days or immediately on any schema-file diff.
- `GENERATED_FOR_BASE_SHA` -- applies to slots 38-40 themselves; valid only
  for the exact `execution_base_sha` and open-PR snapshot recorded in this
  package; regenerate on any drift in either.
- `HISTORICAL_ONLY` -- not used by any slot in this package; reserved for
  future archival-only sources.

## 2. Required Rules

1. Runtime state and open-PR status are always resolved live -- this package
   is a point-in-time snapshot, not a live feed.
2. This package is bound to exactly one `execution_base_sha`
   (`{execution_base_sha}`). A copy of this package without a recorded base
   SHA is advisory only and must not be treated as current-main authority.
3. Any source whose tracked git blob SHA (recorded in
   `39_PROJECT_SOURCE_MANIFEST.json`) differs from the blob at the then-current
   `origin/main` for the same path is stale.
4. Any merged PR touching a watched path family (see
   `40_OPEN_PR_IMPACT_LEDGER.md` section 2) triggers source-set reevaluation
   for this package.
5. Any merged PR affecting a selected source (see the per-PR
   `source_slots_affected` field in the ledger) triggers regeneration of
   those exact slots at minimum, and a full package rebuild is recommended.
6. Any change to the embedded-audit schema (slot 31) or PR Steward
   merge-readiness schema (slot 33) triggers full package regeneration.
7. Any change to the Task Packet canonical schema (slot 25) triggers full
   package regeneration.
8. Any change to the runtime authority manifest (slot 10) triggers full
   package regeneration.
9. A source may remain useful for orientation while stale, but a stale source
   must not be cited to authorize a current implementation or merge
   decision -- re-resolve it live first.
10. Strict isolated-input acceptance work must not be performed inside a
    ChatGPT Project whose inherited files violate the acceptance input gate
    for that work (e.g. a Project still containing files this refresh
    explicitly excluded).
11. Previous package-verification verdicts (e.g. any prior
    `Package Verification Process.txt`-style artifact) are case-specific
    historical records, not a reusable verification process for this or any
    other package.

## 3. Disposition Note

This package's disposition and material-open-PR count are recorded in
`39_PROJECT_SOURCE_MANIFEST.json` (`package_disposition`,
`material_open_pr_count`) and in `40_OPEN_PR_IMPACT_LEDGER.md`. A disposition
of `CURRENT_MAIN_VALID_PENDING_OPEN_PR_REFRESH` means the package is valid for
`{execution_base_sha}` today but must be regenerated if any material PR merges.
No disposition in this family is ever "final forever."
"""


def sh(args: list[str], cwd: Path) -> str:
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True, check=True)
    return result.stdout


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git_blob_sha(repo_root: Path, execution_base_sha: str, path: str) -> str:
    return sh(["git", "rev-parse", f"{execution_base_sha}:{path}"], repo_root).strip()


def git_show_bytes(repo_root: Path, execution_base_sha: str, path: str) -> bytes:
    result = subprocess.run(
        ["git", "show", f"{execution_base_sha}:{path}"],
        cwd=repo_root,
        capture_output=True,
        check=True,
    )
    return result.stdout


def build_copied_slots(repo_root: Path, execution_base_sha: str, source_set: dict, upload_dir: Path) -> list[dict]:
    entries = []
    for slot in source_set["slots"]:
        path = slot["source_path"]
        blob_sha = git_blob_sha(repo_root, execution_base_sha, path)
        data = git_show_bytes(repo_root, execution_base_sha, path)
        out_path = upload_dir / slot["bundle_filename"]
        out_path.write_bytes(data)
        entries.append(
            {
                "slot": slot["slot"],
                "bundle_filename": slot["bundle_filename"],
                "artifact_type": "copied_source",
                "source_path": path,
                "source_commit_sha": execution_base_sha,
                "source_blob_sha": blob_sha,
                "sha256": sha256_bytes(data),
                "bytes": len(data),
                "authority_class": slot["authority_class"],
                "freshness_class": slot["freshness_class"],
                "generated": False,
                "current_main_only": True,
                "open_pr_content_included": False,
                "notes": [slot["rationale"]],
                "rejected_candidates": slot.get("rejected_candidates", []),
            }
        )
    return entries


def load_captured_prs(open_pr_dir: Path) -> list[dict]:
    prs = []
    for f in sorted(open_pr_dir.glob("open-pr-*.json")):
        prs.append(json.loads(f.read_text()))
    return prs


